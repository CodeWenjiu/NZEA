package nzea_rtl

import java.nio.file.{Files, Path}

/** Side artefacts that must travel with the generated RTL.
  *
  * Two mechanisms are exercised:
  *   1. the Verilog body of an external module (firtool only emits the instantiation, like it did for `StatsRegs`); 2.
  *      a text side file next to the RTL (the mechanism `goal/stat-schema.md` depends on).
  *
  * Usage: `PocEmit <outDir> [width]`
  */
object PocEmit:

  def main(args: Array[String]): Unit =
    val outDir = Path.of(if args.nonEmpty then args(0) else "build/poc")
    val width = if args.length > 1 then args(1).toInt else 8
    Files.createDirectories(outDir)
    Files.writeString(outDir.resolve(s"${counterModuleName(width)}.sv"), counterVerilog(counterModuleName(width)))
    Files.writeString(outDir.resolve("Poc.stats.toml"), statsToml(width))
    println(s"wrote ${counterModuleName(width)}.sv and Poc.stats.toml to $outDir")

  private def counterModuleName(width: Int): String = s"PocCounter_w$width"

  /** Must match `PocCounterIO` field order/names, and take the Verilog parameter firtool passes. The register keeps a
    * VPI-readable leaf name.
    */
  private def counterVerilog(name: String): String =
    s"""// Generated by PocEmit — body of the external module declared in Poc.scala.
       |// The `public_flat_rd` metacomment is what makes the register VPI-visible.
       |module $name #(
       |  parameter width = 8
       |) (
       |  input clock,
       |  input resetN,
       |  input incr,
       |  output [31:0] value
       |);
       |  reg [31:0] stat_poc_hits /*verilator public_flat_rd*/;
       |  assign value = stat_poc_hits;
       |  always @(posedge clock) begin
       |    if (!resetN) stat_poc_hits <= '0;
       |    else if (incr) stat_poc_hits <= stat_poc_hits + 1'b1;
       |  end
       |endmodule
       |""".stripMargin

  private def statsToml(width: Int): String =
    s"""# POC placeholder for the RTL-owned stat schema (see goal/stat-schema.md).
       |# Written by the elaboration flow, not by the generator.
       |
       |[region.poc]
       |
       |  [region.poc.stat_poc_hits]
       |  width = 32
       |
       |[derived]
       |  hits_per_bit = "stat_poc_hits / $width"
       |""".stripMargin
