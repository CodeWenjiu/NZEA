// DDR3 memtest for lxb_artix7 — hand-written RV32IM assembly, stack-free.
// Register discipline: loop state strictly in s-registers (puthex/putc
// clobber all t-regs and s0). No stack.
//
// Coverage:
//   1. Full-word write+readback: 0xDEADBEEF ^ i for i in [0, N), word stride
//      4 — exercises every 16B row, both 8B halves, and both 32-bit slots,
//      all bytes written (wstrb=0xF).
//   2. Partial writes: per 16B row, sb touches byte0 and byte8, sh touches
//      half[4:5] and half[12:13]; a readback verifies only strobed bytes
//      changed and the untouched word of the row is intact.
//   3. Overwrite: re-write every word with 0x12345678 ^ i and read back.
//
// UART @ 0x10000000 (bus-backpressured THR), finisher @ 0x00100000.
//
// N=1024 words = 4 KiB, addresses 0x88000000..0x88000FFC (16B rows 0..63).

.equ N, 1024          // words to test (4 KiB)
.equ NROWS, 64        // N / 16 (16B rows)

.section .text
.globl _start
_start:
    la      a0, msg_start
    jal     putstr

    // ---- phase 1: full-word write [0x88000000 + 4i] = 0xDEADBEEF ^ i ----
    li      s3, 0                 // i
    li      s4, N
    lui     s5, 0x88000           // DDR base
    // Pattern base. NOTE: `lui 0xDEADC` mis-assembles under clang (the
    // 20-bit LUI immediate is encoded wrong — see the DDR debug session), so
    // build 0xDEADBEEF with li (lui+addi pair generated by the assembler
    // with correct split).
    li      s6, 0xDEADBEEF        // pattern base
wr_loop:
    xor     s7, s6, s3            // pattern
    slli    s1, s3, 2
    add     s1, s5, s1
    sw      s7, 0(s1)
    addi    s3, s3, 1
    bltu    s3, s4, wr_loop

    la      a0, msg_wr_done
    jal     putstr

    // ---- phase 2: readback + compare phase 1 ----
    li      s3, 0
rd_loop:
    slli    s1, s3, 2
    add     s1, s5, s1
    lw      s2, 0(s1)             // got
    xor     s7, s6, s3            // expected
    bne     s2, s7, rd_fail
    addi    s3, s3, 1
    bltu    s3, s4, rd_loop

    la      a0, msg_rd_ok
    jal     putstr

    // ---- phase 3: partial writes on each 16B row ----
    // Row r base 0x88000000 + 16r:
    //   sb  byte 0      <- 0xA5 + r
    //   sb  byte 8      <- 0x5A ^ r
    //   sh  half [4:5]  <- 0xBEEF
    //   sh  half [12:13]<- 0xF00D
    li      s3, 0                 // row
    lui     s5, 0x88000
    li      s8, NROWS
pw_loop:
    slli    s1, s3, 4
    add     s1, s5, s1
    addi    s6, s3, 0xA5
    andi    s6, s6, 0xFF
    sb      s6, 0(s1)
    li      s7, 0x5A
    xor     s6, s7, s3
    andi    s6, s6, 0xFF
    sb      s6, 8(s1)
    li      s6, 0xBEEF
    sh      s6, 4(s1)
    li      s6, 0xF00D
    sh      s6, 12(s1)
    addi    s3, s3, 1
    bltu    s3, s8, pw_loop

    la      a0, msg_pw_done
    jal     putstr

    // ---- phase 4: verify partial writes ----
    li      s3, 0
    lui     s5, 0x88000
    li      s8, NROWS
pv_loop:
    slli    s1, s3, 4
    add     s1, s5, s1

    // byte 0 == 0xA5 + r
    lbu     s2, 0(s1)
    addi    s7, s3, 0xA5
    andi    s7, s7, 0xFF
    bne     s2, s7, pv_fail

    // byte 8 == 0x5A ^ r
    lbu     s2, 8(s1)
    li      s7, 0x5A
    xor     s7, s7, s3
    andi    s7, s7, 0xFF
    bne     s2, s7, pv_fail

    // half [4:5] == 0xBEEF
    lhu     s2, 4(s1)
    li      s7, 0xBEEF
    bne     s2, s7, pv_fail

    // half [12:13] == 0xF00D
    lhu     s2, 12(s1)
    li      s7, 0xF00D
    bne     s2, s7, pv_fail

    // word1 (offset 4): half[4:5] was replaced; its top half (bytes 6:7)
    // must still be the phase-1 pattern 0xDEADBEEF ^ (4r+1) >> 16.
    // word1 = pattern ^ (4r+1); we want its bits [31:16].
    addi    s7, s3, 0
    slli    s7, s7, 2              // 4r
    addi    s7, s7, 1              // 4r+1
    li      s9, 0xDEADBEEF
    xor     s7, s9, s7             // pattern for index 4r+1
    srli    s7, s7, 16             // keep [31:16]
    lhu     s2, 6(s1)              // bytes 6:7
    // half [12:13] == 0xF00D
    lhu     s2, 12(s1)
    li      s7, 0xF00D
    bne     s2, s7, pv_fail

    // Un-strobed bytes must be preserved. For word1 (offset 4) the strobed
    // half is [4:5], so byte 6 must still be pattern ^ (4r+1) byte 2.
    // pattern(4r+1) = 0xDEADBEEF ^ (4r+1); byte2 of that word = bits [23:16].
    addi    s7, s3, 0
    slli    s7, s7, 2              // 4r
    addi    s7, s7, 1              // 4r+1
    li      s9, 0xDEADBEEF
    xor     s7, s9, s7
    srli    s7, s7, 16             // bits [23:16]
    andi    s7, s7, 0xFF
    lbu     s2, 6(s1)              // byte 6 (un-strobed)
    bne     s2, s7, pv_fail

    // word2 (offset 8): strobed byte is 8, so byte 9 must be pattern ^ (4r+2)
    // byte 1 (bits [15:8]).
    addi    s7, s3, 0
    slli    s7, s7, 2
    addi    s7, s7, 2              // 4r+2
    xor     s7, s9, s7
    srli    s7, s7, 8              // bits [15:8]
    andi    s7, s7, 0xFF
    lbu     s2, 9(s1)
    bne     s2, s7, pv_fail

    // word0 (offset 0): strobed byte is 0, so byte 1 must be pattern ^ (4r+0)
    // byte 1 (bits [15:8]).
    addi    s7, s3, 0
    slli    s7, s7, 2              // 4r
    xor     s7, s9, s7
    srli    s7, s7, 8              // bits [15:8]
    andi    s7, s7, 0xFF
    lbu     s2, 1(s1)
    bne     s2, s7, pv_fail

    // word3 (offset 12): strobed half is [12:13], so byte 14 must be pattern
    // ^ (4r+3) byte 2 (bits [23:16]).
    addi    s7, s3, 0
    slli    s7, s7, 2
    addi    s7, s7, 3              // 4r+3
    xor     s7, s9, s7
    srli    s7, s7, 16             // bits [23:16]
    andi    s7, s7, 0xFF
    lbu     s2, 14(s1)
    bne     s2, s7, pv_fail

    addi    s3, s3, 1
    bltu    s3, s8, pv_loop

    la      a0, msg_pv_ok
    jal     putstr

    // ---- phase 5: overwrite all words with 0x12345678 ^ i, read back ----
    li      s3, 0
    li      s4, N
    lui     s5, 0x88000
    li      s6, 0x12345678
ow_loop:
    xor     s7, s6, s3
    slli    s1, s3, 2
    add     s1, s5, s1
    sw      s7, 0(s1)
    addi    s3, s3, 1
    bltu    s3, s4, ow_loop

    li      s3, 0
or_loop:
    slli    s1, s3, 2
    add     s1, s5, s1
    lw      s2, 0(s1)
    xor     s7, s6, s3
    bne     s2, s7, ov_fail
    addi    s3, s3, 1
    bltu    s3, s4, or_loop

    la      a0, msg_ok
    jal     putstr
    lui     t0, 0x00100
    sw      x0, 0(t0)             // finisher: LED on
    j       done

rd_fail:
    // phase 2: s3 = index, s2 = got, s7 = expected.
    la      a0, msg_fail1
    j       report

pv_fail:
    // phase 4: s3 = row, s2 = got, s7 = expected.
    la      a0, msg_fail2
    j       report

ov_fail:
    // phase 5: s3 = index, s2 = got, s7 = expected.
    la      a0, msg_fail3

report:
    mv      s8, s3
    mv      s9, s2
    jal     putstr                 // print phase tag (a0 already set)
    mv      a0, s8
    jal     puthex
    li      a1, ' '
    jal     putc
    la      a0, msg_got
    jal     putstr
    mv      a0, s9
    jal     puthex
    li      a1, ' '
    jal     putc
    la      a0, msg_exp
    jal     putstr
    mv      a0, s7
    jal     puthex
    li      a1, '\n'
    jal     putc
    // ---- dump the failing row's 4 words (aligned to 16B) ----
    // s8 = index (phase 2/5) or row (phase 4). Word index for phases 2/5:
    // row = index >> 2. For phase 4 s8 is already the row.
    // puthex clobbers all t-regs and s0; loop state in s4..s6 (dead after
    // the failing loop exits, so reuse is safe).
    li      a0, 4
    bltu    a0, s3, 1f            // if s3 >= 4 it is a word index (phase 2/5)
    // s3 is a row (phase 4) — use directly
    mv      s4, s3
    j       2f
1:  srli    s4, s3, 2             // row = word index >> 2
2:  slli    s4, s4, 4            // row base offset
    lui     s5, 0x88000
    add     s5, s5, s4           // row base addr
    li      s6, 0                // word offset
3:  mv      a0, s5
    lw      a0, 0(a0)
    jal     puthex
    li      a1, ' '
    jal     putc
    addi    s5, s5, 4
    addi    s6, s6, 1
    li      t3, 4
    bltu    s6, t3, 3b
    li      a1, '\n'
    jal     putc

done:
    j       done

// UART/hex helpers (putc/putstr/puthex) come from common.S, appended by asm2hex.

.section .rodata
msg_start: .asciz "DDR memtest start\n"
msg_wr_done: .asciz "WRDONE\n"
msg_rd_ok:  .asciz "RDOK\n"
msg_pw_done: .asciz "PWDONE\n"
msg_pv_ok:  .asciz "PVOK\n"
msg_ok:     .asciz "DDR OK\n"
msg_fail1:  .asciz "P1 FAIL @"
msg_fail2:  .asciz "P2 FAIL @"
msg_fail3:  .asciz "P3 FAIL @"
msg_got:    .asciz "got="
msg_exp:    .asciz " exp="
