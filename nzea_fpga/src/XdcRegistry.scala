package nzea_fpga

import scala.collection.mutable

import nzea_rtl.{DumpRegistry, FileList}

/** The constraints a dump writes beside the RTL they bind: one file per owner, written only for the parts the design
  * actually used, and listed in `xcdfiles.f` for the project generator.
  *
  * A constraint binds by name, so it is only ever valid against the top it was written for: an XDC line for a port the
  * design does not declare is an error in Vivado, and a port the design declares with no line is a pin the tools would
  * place themselves. Both halves are the business of the part that declares the pins ([[nzea_fpga.boards.lxb_artix7.BoardXdc]],
  * [[nzea_fpga.device.ddr3.Ddr3Xdc]]), which registers its text where the design uses it ([[DumpRegistry]]).
  *
  * What registration decides is *which* constraints travel with a build, never what they say: pins, I/O standards and
  * timing exceptions are the board's facts, curated by hand against the vendor's reference and the device's documents.
  */
object XdcRegistry:

    /** The owners that registered, in first-use order — one file per owner, named after it. */
    private val owners = mutable.LinkedHashMap.empty[String, () => String]

    /** The dump-emitter key the writer rides: constraints travel with the RTL they bind ([[DumpRegistry.emitAll]]). */
    private val WriterKey = "xdc"

    DumpRegistry.onReset(() => owners.clear())

    /** Register `owner`'s `<owner>.xdc` text. Registering an owner twice keeps the first, so a part instantiated many
      * times still writes one file (like every other emitter's key, [[DumpRegistry.onEmit]]).
      */
    def onEmit(owner: String)(text: => String): Unit =
        if !owners.contains(owner) then
            owners(owner) = () => text
            DumpRegistry.onEmit(WriterKey)(writeAll)

    private def writeAll(dir: os.Path): Unit =
        os.makeDir.all(dir)
        for ((owner, text) <- owners) do
            val body = text()
            os.write.over(dir / s"$owner.xdc", marker(owner) + (if body.endsWith("\n") then body else body + "\n"))
        FileList.writeXdc(dir, owners.keysIterator.map(_ + ".xdc").toSeq)

    private def marker(owner: String): String =
        s"""# Generated by nzea's fpga dump — the "$owner" constraints; do not edit.
           |# The text lives in the tree, registered where the design used it (`nzea_fpga.XdcRegistry`, one file per owner).
           |""".stripMargin
